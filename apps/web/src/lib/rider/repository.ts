import 'server-only';
import { createClient } from '@/lib/supabase/server';
import { generateStarterRider, type GeneratedRider } from './generate';
import type { SegmentLevel } from './development';

/**
 * Server-side rider persistence. Everything here runs with the logged-in
 * player's session, so RLS guarantees a player only ever touches their own row.
 */

/**
 * The only form in which the hidden development values reach the app: 1-5
 * estimates computed in the database (my_rider_estimates()). The raw Potential /
 * Trainability / Professionalism / Recovery are not readable by any client role
 * (column grants, migration 04) and are not part of StoredRider.
 */
export interface DevelopmentLevels {
  potentialStars: SegmentLevel;
  trainabilityLevel: SegmentLevel;
  professionalismLevel: SegmentLevel;
  recoveryLevel: SegmentLevel;
}

/** Columns a client role may read (must match the column GRANT in migration 04). Never `*`. */
export const RIDER_PUBLIC_COLUMNS =
  'id, player_id, first_name, surname, country_name, country_iso2, age, attributes, condition, condition_previous, inferred_archetype, generator_version, is_ai, created_at';

export interface StoredRider extends Omit<GeneratedRider, 'potential' | 'trainability' | 'professionalism' | 'recovery'> {
  id: string;
  /** True for AI/test fillers generated by the Rookie AI Generator V1 (no player_id). */
  isAi: boolean;
  /**
   * A snapshot of `condition` as it was immediately before the most recent
   * write — the only thing that lets the UI show a real up/down/flat trend
   * instead of guessing. Equal to `condition` until the first processed
   * training (see lib/training/engine.ts), so a fresh rider reads as flat.
   */
  conditionPrevious: StoredRider['condition'];
  /** 1-5 estimates only — see DevelopmentLevels. */
  estimates: DevelopmentLevels;
}

function fromRow(row: Record<string, unknown>, estimates: DevelopmentLevels = UNKNOWN_ESTIMATES): StoredRider {
  return {
    id: row.id as string,
    firstName: row.first_name as string,
    surname: row.surname as string,
    countryName: row.country_name as string,
    countryIso2: row.country_iso2 as string,
    age: row.age as number,
    attributes: row.attributes as StoredRider['attributes'],
    condition: row.condition as StoredRider['condition'],
    conditionPrevious: (row.condition_previous as StoredRider['condition']) ?? (row.condition as StoredRider['condition']),
    inferredArchetype: row.inferred_archetype as string,
    generatorVersion: row.generator_version as string,
    isAi: Boolean(row.is_ai),
    estimates,
  };
}

/** Only used for riders whose estimates are not available to the caller (e.g. AI fillers in admin lists). */
const UNKNOWN_ESTIMATES: DevelopmentLevels = { potentialStars: 1, trainabilityLevel: 1, professionalismLevel: 1, recoveryLevel: 1 };

async function getMyEstimates(): Promise<DevelopmentLevels | null> {
  const supabase = await createClient();
  const { data, error } = await supabase.rpc('my_rider_estimates');
  const row = Array.isArray(data) ? data[0] : data;
  if (error || !row) return null;
  return {
    potentialStars: row.potential_stars as SegmentLevel,
    trainabilityLevel: row.trainability_level as SegmentLevel,
    professionalismLevel: row.professionalism_level as SegmentLevel,
    recoveryLevel: row.recovery_level as SegmentLevel,
  };
}

/** The current player's rider, or null if they have none yet. */
export async function getMyRider(): Promise<StoredRider | null> {
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return null;

  const { data, error } = await supabase
    .from('riders')
    .select(RIDER_PUBLIC_COLUMNS)
    .eq('player_id', user.id)
    .maybeSingle();

  if (error || !data) return null;
  const estimates = await getMyEstimates();
  if (!estimates) return null;
  return fromRow(data as unknown as Record<string, unknown>, estimates);
}

/**
 * Ensure the current player has exactly one starter rider.
 *
 * Idempotent by design: if a rider already exists it is returned untouched and
 * NOTHING is regenerated. Only a brand-new player triggers generation. The
 * UNIQUE(player_id) constraint is the final backstop against a race between two
 * simultaneous requests — the loser's insert fails and we re-read the winner's
 * row.
 */
export async function ensureStarterRider(): Promise<StoredRider | null> {
  const existing = await getMyRider();
  if (existing) return existing;

  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return null;

  const rider = generateStarterRider(Math.random);

  // The database validates the payload against the generator's bounds and owns
  // the insert (create_my_starter_rider, migration 04): a client can no longer
  // write the riders table directly, and the function is idempotent — if a
  // concurrent request already created the rider it simply returns that one.
  // It also creates the rider's bike (Bike Condition V1, lib/facilities/bike.ts).
  const { error } = await supabase.rpc('create_my_starter_rider', {
    p_rider: {
      first_name: rider.firstName,
      surname: rider.surname,
      country_name: rider.countryName,
      country_iso2: rider.countryIso2,
      age: rider.age,
      attributes: rider.attributes,
      condition: rider.condition,
      inferred_archetype: rider.inferredArchetype,
      potential: rider.potential,
      trainability: rider.trainability,
      professionalism: rider.professionalism,
      recovery: rider.recovery,
      generator_version: rider.generatorVersion,
    },
  });
  // On error (e.g. a concurrent request won the race) just re-read: whatever
  // exists for this player is returned; nothing is ever regenerated.
  void error;
  return getMyRider();
}

/**
 * Every rider currently in the game — the real player(s) and any AI fillers.
 * Used by the admin/test peloton view only; not part of any player-facing page.
 */
export async function listAllRiders(): Promise<StoredRider[]> {
  const supabase = await createClient();
  const { data, error } = await supabase
    .from('riders')
    .select(RIDER_PUBLIC_COLUMNS)
    .order('is_ai', { ascending: true })
    .order('created_at', { ascending: true });

  if (error || !data) return [];
  return (data as unknown as Record<string, unknown>[]).map((row) => fromRow(row));
}

